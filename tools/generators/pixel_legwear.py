FIXED = {"s": ("e8eef2", "9aa4ac"), "y": "f8e08a", "Y": "d8a83a", "z": "8a6020"}


def _rgb(value):
    return tuple(int(value[i:i + 2], 16) for i in (0, 2, 4))


def _shift(rgb, dl, dh=0.0, ds=0.0):
    h, l, s = colorsys.rgb_to_hls(*(c / 255 for c in rgb))
    r, g, b = colorsys.hls_to_rgb((h + dh) % 1.0, max(0.02, min(0.96, l + dl)), max(0.0, min(1.0, s + ds)))
    return round(r * 255), round(g * 255), round(b * 255)


def _mix(a, b, t):
    return tuple(round(x + (y - x) * t) for x, y in zip(a, b))


def material(main, light):
    """Six tones, specular first: warm lights from `light`, cool saturated shadows below `main`."""
    return [_shift(light, 0.16, -0.01, -0.04), light, _mix(light, main, 0.5), main,
            _shift(main, -0.11, 0.015, 0.05), _shift(main, -0.2, 0.03, 0.08)]


def accent_ramp(accent):
    return [_shift(accent, 0.14, -0.01), accent, _shift(accent, -0.13, 0.015, 0.04), _shift(accent, -0.25, 0.03, 0.06)]


def _colours(colors, extras):
    main, light, accent = (_rgb(c) for c in colors)
    body = material(main, light)
    trim = accent_ramp(accent) if "trim" in extras else [body[2], body[3], body[4], body[5]]
    leather = [tuple(c[:3]) for c in pal.LEATHER]
    lookup = {str(i + 1): tone for i, tone in enumerate(body)}
    lookup["0"] = _mix(body[0], (255, 255, 250), 0.55)
    lookup.update(dict(zip("abcd", trim)))
    lookup.update({"l": leather[2], "m": leather[4], "n": leather[6]})
    lookup.update({"y": _rgb(FIXED["y"]), "Y": _rgb(FIXED["Y"]), "z": _rgb(FIXED["z"])})
    lookup.update({"s": _rgb(FIXED["s"][0]), "e": accent, "E": _shift(accent, 0.22), "o": (24, 18, 20)})
    fur = [_mix(_rgb("ece4d0"), light, 0.3), _mix(_rgb("c8b898"), main, 0.3), _mix(_rgb("8a7a60"), main, 0.4)]
    lookup.update(dict(zip("FGH", fur if "fur" in extras else trim[:3])))
    lookup.update({"p": _rgb("eef2f4"), "q": _rgb("a8b0b8"), "r": _rgb("5a6068")})
    lookup.update({"v": _mix(_rgb("9ad85a"), light, 0.2), "w": _rgb("4c9a34"), "x": _rgb("2a5a22")})
    lookup.update({"f": _rgb("fff0a0"), "g": _rgb("ff9a2a"), "h": _rgb("c8341c")})
    lookup.update({"u": _rgb("b8642a"), "U": _rgb("7a3a1c"), "i": _rgb("f4fbff"), "I": _rgb("9ad0f0"),
                   "k": _rgb("f0ead8"), "K": _rgb("a89c84")})
    return lookup


def _reoutline(grid):
    size = len(grid)
    out = [r[:] for r in grid]
    for y in range(size):
        for x in range(size):
            if grid[y][x] == "." and any(0 <= x + dx < size and 0 <= y + dy < size and grid[y + dy][x + dx] not in ".o"
                                         for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                out[y][x] = "o"
    return out


BOOT_SHAPES = ("sabatons", "striders", "boots", "slippers")


def icon(style, extras, colors, kind=""):
    """RGBA rows (None for transparent) of one legwear icon: the item's own piece, else its shape's."""
    lookup = _colours(colors, extras)
    grid = [list(row) for row in PIECES.get(kind, MASTERS[style])]
    painted = False
    # Boots drawn from scratch carry their own ornaments; overlays only decorate the masters.
    for extra in ([] if kind in PIECES and style in BOOT_SHAPES else extras):
        for x0, y0, patch in OVERLAYS.get((style, extra), []):
            for dy, row in enumerate(patch):
                for dx, ch in enumerate(row):
                    if ch != ".":
                        grid[y0 + dy][x0 + dx] = ch
                        painted = True
    if painted:
        grid = _reoutline(grid)
    rows = ["".join(r) for r in grid]
    return [[(lookup[ch] + (255,)) if ch != "." else None for ch in row] for row in rows]
