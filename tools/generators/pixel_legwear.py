"""Hand-pixelled leg armour and boot icons (32x32) in the classic item-icon style: legs seen from
in front and a little above (belt, hip plates, thighs, knees, shins), boots as a pair in a
three-quarter view with the left boot a step ahead, lit from the top-left.

Each master is 32 rows of 32 letters, one per pixel ("." transparent). Letters:

  o outline (icon_finish tints it)       0 hot specular, 1-6 the item's material, light to deepest
  a b c d trim: the accent colour when the look has "trim", else a deeper band of the material
  F G H cuff: fur when the look has "fur", else trim
  l m n leather (belt, straps)           y Y z gold (buckles), light to dark
  s rivet (steel)                        e E the accent (a gem or stitch), its highlight

  p q r spike steel   v w x leaf greens   f g h flame (hot to ember)
  u U rust   i I ice   k K bone

Extras ("spikes", "leaves", "runes", "flames") paint OVERLAYS patches over the master, which is
outlined again; "fur" turns the F G H cuffs into fur.
make_sprites.py calls icon(style, look extras, colors).
"""

